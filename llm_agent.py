"""
Project Synthexis - Multimodal LLM Synthesis Engine
Handles query synthesis, context grounding, and vision analysis via Google Gemini.
"""

import os
import logging
from typing import List, Optional, Any
import requests
from dotenv import load_dotenv

# Load environment variables
load_dotenv()

logger = logging.getLogger("synthexis.llm")

GEMINI_API_KEY = os.getenv("GEMINI_API_KEY", "")
GEMINI_API_ENDPOINT = "https://generativelanguage.googleapis.com/v1beta/models"

# Resilient model priority cascade
PREFERRED_MODELS = [
    "gemini-flash-lite-latest",
    "gemini-3.8-flash",
    "gemini-flash-latest",
    "gemini-2.5-pro"
]

def generate_synthesis(query: str, context: List[str], images: Optional[List[Any]] = None) -> str:
    """
    Synthesizes a response to the query using retrieved text chunks and visual data.
    
    Args:
        query: User question or comparison instruction.
        context: List of retrieved context strings.
        images: Optional list of base64 data URIs or image bytes.
        
    Returns:
        Structured Markdown response string grounded in the provided evidence.
    """
    api_key = os.getenv("GEMINI_API_KEY", GEMINI_API_KEY)
    if not api_key:
        return (
            "⚠️ **API Key Missing**: `GEMINI_API_KEY` is not set in `.env`.\n\n"
            "Please provide a Gemini API key to activate generative multimodal answers."
        )

    # Format context chunks
    formatted_context = ""
    if context:
        chunks_text = "\n\n".join([f"--- Evidence Chunk #{i+1} ---\n{chunk}" for i, chunk in enumerate(context)])
        formatted_context = f"## Retrieved Document Context:\n{chunks_text}\n"
    else:
        formatted_context = "No specific context chunks were retrieved from the document store."

    system_instruction = (
        "You are Synthexis, an advanced multi-modal document synthesis intelligence. "
        "Your task is to answer the user query accurately and comprehensively, basing your analysis "
        "strictly on the provided document context and attached figures/diagrams.\n\n"
        "Guidelines:\n"
        "1. Ground your answers strictly in the retrieved evidence. Do not extrapolate or hallucinate facts.\n"
        "2. Directly cite document names, sections, and page numbers when making claims (e.g. `[Document.pdf | Page 2]`).\n"
        "3. If visual figures or charts are provided, interpret them to extract quantitative trends, labels, and data points.\n"
        "4. Format your output with clear Markdown headings, bullet points, and tables where appropriate.\n"
        "5. If the retrieved context is insufficient to answer a portion of the question, clearly state what information is missing."
    )

    prompt_body = (
        f"{system_instruction}\n\n"
        f"{formatted_context}\n\n"
        f"## User Query:\n{query}\n\n"
        f"## Synthesis Answer:"
    )

    # Build Gemini multimodal parts payload
    parts = []
    
    # Attach visual data if available
    if images:
        for img in images:
            if isinstance(img, str) and img.startswith("data:image"):
                try:
                    header, b64_data = img.split(",", 1)
                    mime_type = header.split(";")[0].replace("data:", "")
                    parts.append({
                        "inline_data": {
                            "mime_type": mime_type,
                            "data": b64_data
                        }
                    })
                except Exception as e:
                    logger.warning(f"Failed to parse base64 image data: {e}")

    # Add text prompt
    parts.append({"text": prompt_body})

    payload = {
        "contents": [{"parts": parts}],
        "generationConfig": {
            "temperature": 0.2,
            "maxOutputTokens": 2048
        }
    }

    # Attempt generation across available models
    last_error = ""
    for model_name in PREFERRED_MODELS:
        url = f"{GEMINI_API_ENDPOINT}/{model_name}:generateContent?key={api_key}"
        try:
            res = requests.post(url, json=payload, timeout=30)
            if res.status_code == 200:
                data = res.json()
                candidates = data.get("candidates", [])
                if candidates:
                    parts = candidates[0].get("content", {}).get("parts", [])
                    if parts and "text" in parts[0]:
                        return parts[0]["text"]
                return "No text response generated by the model."
            elif res.status_code in [404, 503, 429]:
                last_error = f"{model_name}: HTTP {res.status_code}"
                logger.warning(f"Model {model_name} returned {res.status_code}, trying fallback...")
                continue
            else:
                last_error = f"API error ({res.status_code}): {res.text[:200]}"
                break
        except Exception as e:
            last_error = str(e)
            logger.warning(f"Connection error with {model_name}: {e}")
            continue

    return f"⚠️ **Synthesis Error**: Could not generate answer from Gemini API.\n\n*Details:* `{last_error}`"
